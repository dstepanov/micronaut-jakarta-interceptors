package io.micronaut.interceptor.test.ordering;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Has the visitor of the tests rewrite the {@code @Order} of the class into its priority negated, as Micronaut CDI
 * does for a selected alternative.
 */
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.TYPE)
public @interface NegatesItsPriority {
}
